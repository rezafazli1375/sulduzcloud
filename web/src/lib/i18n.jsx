const dictionaries = { fa, en };

const I18nContext = createContext(null);

function lookup(dict, path) {
  return path.split('.').reduce((acc, key) => (acc && typeof acc === 'object' ? acc[key] : undefined), dict);
}

function interpolate(text, vars) {
  if (!vars) return text;
  return String(text).replace(/\{(\w+)\}/g, (_, key) => (vars[key] !== undefined ? vars[key] : `{${key}}`));
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('sc_lang') || 'fa');

  useEffect(() => {
    localStorage.setItem('sc_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  }, [lang]);

  const setLang = useCallback((next) => {
    setLangState(next === 'en' ? 'en' : 'fa');
  }, []);

  const t = useCallback(
    (key, vars) => {
      const value = lookup(dictionaries[lang], key);
      if (value !== undefined) return interpolate(value, vars);
      const fallback = lookup(dictionaries.en, key);
      return fallback !== undefined ? interpolate(fallback, vars) : key;
    },
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang, t, dir: lang === 'fa' ? 'rtl' : 'ltr', isRtl: lang === 'fa' }),
    [lang, setLang, t]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside LanguageProvider');
  return ctx;
}

export function translateError(err, t) {
  const code = err?.code;
  const map = {
    insufficient_balance: 'errors.insufficientBalance',
    limit_configs: 'errors.limitConfigs',
    limit_total_gb: 'errors.limitGb',
    limit_gb_per_config: 'errors.limitGb',
    limit_days_per_config: 'errors.limitDays',
    network: 'errors.network',
    forbidden: 'errors.forbidden',
    owner_only: 'errors.forbidden',
    server_in_use: 'errors.serverInUse',
    invalid_url: 'errors.invalidUrl',
    server_not_found: 'errors.serverNotFound',
    xui_not_configured: 'errors.xuiNotConfigured',
  };
  if (map[code]) return t(map[code]);
  return err?.message || t('errors.generic');
}
